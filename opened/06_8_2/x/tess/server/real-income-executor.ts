async function scanAndClaimAirdrops(): Promise<string[]> {
  const results: string[] = [];
  const wallet = FATHER_WALLET;
  const maskedWallet = wallet.length >= 10
    ? `${wallet.slice(0, 6)}...${wallet.slice(-4)}`
    : "(wallet not configured)";
  log(`Scanning airdrops for wallet: ${maskedWallet}`);
  results.push(`Wallet: ${maskedWallet}`);
  
  try {
    const solRes = await axios.post("https://api.mainnet-beta.solana.com", {
      jsonrpc: "2.0",
      id: 1,
      method: "getBalance",
      params: [FATHER_WALLET],
    }, { timeout: 10000 });
    
    const balance = (solRes.data?.result?.value || 0) / 1e9;
    results.push(`Wallet balance: ${balance.toFixed(6)} SOL`);
    
    const sigRes = await axios.post("https://api.mainnet-beta.solana.com", {
      jsonrpc: "2.0",
      id: 1,
      method: "getSignaturesForAddress",
      params: [FATHER_WALLET, { limit: 10 }],
    }, { timeout: 10000 });
    
    const sigs = sigRes.data?.result || [];
    results.push(`Recent transactions: ${sigs.length}`);
    
    const tokenRes = await axios.post("https://api.mainnet-beta.solana.com", {
      jsonrpc: "2.0",
      id: 1,
      method: "getTokenAccountsByOwner",
      params: [FATHER_WALLET, { programId: "TokenkegQfeZyiNwAJbNbGKPFXCWuBvf9Ss623VQ5DA" }, { encoding: "jsonParsed" }],
    }, { timeout: 10000 });
    
    const tokenAccounts = tokenRes.data?.result?.value || [];
    for (const ta of tokenAccounts) {
      const info = ta.account?.data?.parsed?.info;
      if (info && parseFloat(info.tokenAmount?.uiAmount || "0") > 0) {
        results.push(`Token found: ${info.mint} — balance: ${info.tokenAmount.uiAmount}`);
      }
    }

    try {
      const jupRes = await axios.get(`https://token.jup.ag/strict`, { timeout: 10000 });
      const topTokens = (jupRes.data || []).slice(0, 20);
      for (const token of topTokens.slice(0, 5)) {
        results.push(`Jupiter tracked: ${token.symbol} (${token.name})`);
      }
    } catch {}

  } catch (e: any) {
    results.push(`Wallet scan error: ${e.message}`);
  }

  return results;
}

