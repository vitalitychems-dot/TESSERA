const log = (msg: string) => console.log(`[RealIncome] ${msg}`);
const FATHER_WALLET = process.env.SOL_WALLET || "";
const STATE_FILE = "server/real-income-state.json";

interface BountySolution {
  issueUrl: string;
  repo: string;
  title: string;
  solution: string;
  commentPosted: boolean;
  commentUrl?: string;
  timestamp: number;
}

interface IncomeProof {
  method: string;
  amount: number;
  currency: string;
  proof: string;
  timestamp: number;
  verified: boolean;
}

interface ExecutorState {
  bountiesSolved: BountySolution[];
  incomeProofs: IncomeProof[];
  articlesPublished: number;
  servicesFullfilled: number;
  totalAttempts: number;
  lastRun: number;
  strategiesTriedAndResults: { strategy: string; result: string; timestamp: number }[];
}

let state: ExecutorState = {
  bountiesSolved: [],
  incomeProofs: [],
  articlesPublished: 0,
  servicesFullfilled: 0,
  totalAttempts: 0,
  lastRun: 0,
  strategiesTriedAndResults: [],
};

function loadState() {
  try {
    if (fs.existsSync(STATE_FILE)) {
      const loaded = JSON.parse(fs.readFileSync(STATE_FILE, "utf-8"));
      state = { ...state, ...loaded };
    }
  } catch {}
}

function saveState() {
  try {
    fs.writeFileSync(STATE_FILE, JSON.stringify(state, null, 2));
  } catch {}
}

loadState();

async function solveBountyForReal(issueUrl: string, repo: string, title: string, body: string): Promise<BountySolution> {
  log(`SOLVING BOUNTY: "${title}" in ${repo}`);
  
  const solution = await callLLMSimple(
    `You are a senior software engineer solving a GitHub bounty issue.

ISSUE TITLE: ${title}
REPOSITORY: ${repo}
ISSUE BODY:
${body.slice(0, 3000)}

Write a complete, production-ready solution. Include:
1. Explanation of the root cause
2. The exact code changes needed (with file paths)
3. Any tests that should be added

Format your response as a professional GitHub comment that could be posted directly.
Start with "## Solution" and be thorough but concise.`,
    4096
  );

  const bounty: BountySolution = {
    issueUrl,
    repo,
    title,
    solution,
    commentPosted: false,
    timestamp: Date.now(),
  };

  const token = process.env.GITHUB_TOKEN || process.env.GITHUB_PERSONAL_ACCESS_TOKEN;
  if (token && issueUrl.includes("github.com")) {
    try {
      const apiUrl = issueUrl
        .replace("https://github.com/", "https://api.github.com/repos/")
        .replace(/\/issues\/(\d+)/, "/issues/$1/comments");
      
      const commentBody = `${solution}\n\n---\n*Generated by Tessera AI — solving bounties autonomously. [Learn more](tess://tessera.sovereign)*`;
      
      const res = await axios.post(apiUrl, { body: commentBody }, {
        headers: {
          Authorization: `token ${token}`,
          Accept: "application/vnd.github.v3+json",
        },
        timeout: 15000,
      });
      
      if (res.status === 201) {
        bounty.commentPosted = true;
        bounty.commentUrl = res.data?.html_url;
        log(`BOUNTY COMMENT POSTED: ${bounty.commentUrl}`);
      }
    } catch (e: any) {
      log(`Comment failed (${e.response?.status || e.message}) — trying fork+PR approach`);
      try {
        const repoPath = repo.replace("https://github.com/", "");
        const forkRes = await axios.post(`https://api.github.com/repos/${repoPath}/forks`, {}, {
          headers: { Authorization: `token ${token}`, Accept: "application/vnd.github.v3+json" },
          timeout: 15000,
        });
        if (forkRes.status === 202 || forkRes.status === 200) {
          bounty.commentUrl = forkRes.data?.html_url;
          log(`FORKED REPO: ${bounty.commentUrl} — solution saved, PR can be created`);
        }
      } catch (forkErr: any) {
        log(`Fork also failed (${forkErr.response?.status || forkErr.message}) — solution saved locally`);
      }
    }
  }

  state.bountiesSolved.push(bounty);
  saveState();
  return bounty;
}

async function findAndSolveBounties(): Promise<BountySolution[]> {
  const token = process.env.GITHUB_TOKEN || process.env.GITHUB_PERSONAL_ACCESS_TOKEN;
  const headers: any = { Accept: "application/vnd.github.v3+json", "User-Agent": "Tessera-Bounty-Solver" };
  if (token) headers.Authorization = `token ${token}`;

  const solved: BountySolution[] = [];
  const searches = [
    "label:bounty state:open is:issue sort:created-desc language:typescript",
    "label:bounty state:open is:issue sort:created-desc language:javascript",
    "label:bounty state:open is:issue sort:created-desc language:python",
    "label:reward state:open is:issue sort:created-desc",
    "label:help-wanted state:open language:typescript sort:updated-desc",
    "label:help-wanted state:open language:javascript sort:updated-desc",
    "label:good-first-issue state:open language:typescript sort:created-desc",
    "\"bug bounty\" state:open is:issue sort:created-desc",
  ];

  for (const q of searches) {
    if (solved.length >= 5) break;
    try {
      const encodedQ = encodeURIComponent(q);
      const res = await axios.get(`https://api.github.com/search/issues?q=${encodedQ}&per_page=5`, { headers, timeout: 15000 });
      const items = res.data?.items || [];
      log(`Search "${q.slice(0, 50)}..." returned ${items.length} results`);

      for (const item of items.slice(0, 3)) {
        if (solved.length >= 5) break;
        const alreadySolved = state.bountiesSolved.some(b => b.issueUrl === item.html_url);
        if (alreadySolved) continue;

        try {
          const body = item.body || "No description provided";
          const bounty = await solveBountyForReal(
            item.html_url,
            item.repository_url?.replace("https://api.github.com/repos/", "") || "unknown",
            item.title,
            body
          );
          solved.push(bounty);
          await new Promise(r => setTimeout(r, 2000));
        } catch (e: any) {
          log(`Failed to solve "${item.title}": ${e.message}`);
        }
      }
      await new Promise(r => setTimeout(r, 1000));
    } catch (e: any) {
      const status = e.response?.status;
      log(`Search failed for "${q.slice(0, 40)}...": ${status || e.message}`);
      if (status === 401) {
        log("GitHub token unauthorized (401) — skipping all bounty searches. Check GITHUB_TOKEN validity and scopes.");
        break;
      }
      if (status === 403) {
        log("GitHub rate limit hit — pausing bounty scan");
        break;
      }
    }
  }

  state.totalAttempts++;
  state.lastRun = Date.now();
  saveState();
  return solved;
}

