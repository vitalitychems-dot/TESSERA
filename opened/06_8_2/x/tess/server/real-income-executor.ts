async function runFullIncomeExecution(): Promise<{
  bounties: BountySolution[];
  affiliateResults: string[];
  airdropResults: string[];
  articleResult: string;
  discussionContent: string;
  summary: string;
}> {
  log("=== FULL REAL INCOME EXECUTION STARTING ===");
  state.totalAttempts++;
  state.lastRun = Date.now();

  const [bounties, affiliateResults, airdropResults, articleResult, discussionContent] = await Promise.allSettled([
    findAndSolveBounties(),
    executeRealAffiliateSetup(),
    scanAndClaimAirdrops(),
    publishSEOArticleNow(),
    createTesseractIncomeDiscussion(),
  ]);

  const results = {
    bounties: bounties.status === "fulfilled" ? bounties.value : [],
    affiliateResults: affiliateResults.status === "fulfilled" ? affiliateResults.value : [`Error: ${(affiliateResults as any).reason?.message}`],
    airdropResults: airdropResults.status === "fulfilled" ? airdropResults.value : [`Error: ${(airdropResults as any).reason?.message}`],
    articleResult: articleResult.status === "fulfilled" ? articleResult.value : `Error: ${(articleResult as any).reason?.message}`,
    discussionContent: discussionContent.status === "fulfilled" ? discussionContent.value : `Error: ${(discussionContent as any).reason?.message}`,
    summary: "",
  };

  const summaryParts = [
    `Bounties solved: ${results.bounties.length} (${results.bounties.filter(b => b.commentPosted).length} comments posted)`,
    `Article: ${results.articleResult.slice(0, 100)}`,
    `Airdrop scan: ${results.airdropResults.length} findings`,
    `Affiliate: ${results.affiliateResults.length} actions`,
  ];
  results.summary = summaryParts.join(" | ");

  log(`=== EXECUTION COMPLETE: ${results.summary} ===`);

  for (const b of results.bounties) {
    state.strategiesTriedAndResults.push({
      strategy: "bounty-solving",
      result: b.commentPosted ? `Posted solution to ${b.issueUrl}` : `Generated solution for ${b.title} (no comment posted)`,
      timestamp: Date.now(),
    });
  }
  state.strategiesTriedAndResults.push({
    strategy: "seo-article",
    result: results.articleResult.slice(0, 200),
    timestamp: Date.now(),
  });
  state.strategiesTriedAndResults.push({
    strategy: "airdrop-scan",
    result: results.airdropResults.join("; ").slice(0, 200),
    timestamp: Date.now(),
  });

  if (state.strategiesTriedAndResults.length > 100) {
    state.strategiesTriedAndResults = state.strategiesTriedAndResults.slice(-100);
  }

  saveState();
  return results;
}

