import { Connection, PublicKey, Keypair, Transaction, SystemProgram, LAMPORTS_PER_SOL, sendAndConfirmTransaction } from "@solana/web3.js";
import bs58 from "bs58";
import fs from "fs";
import path from "path";

const FATHER_ADDRESS = process.env.SOL_WALLET || "";
const COMMUNITY_ADDRESS = process.env.SOL_WALLET || "";
const GENERATED_KEY_PATH = path.join(process.cwd(), ".local", "sol-keypair.json");
const RPC_ENDPOINTS = [
  "https://api.mainnet-beta.solana.com",
  "https://solana-mainnet.g.alchemy.com/v2/demo",
];

let connection: Connection | null = null;
let walletKeypair: Keypair | null = null;
let walletInitialized = false;
let walletAutoGenerated = false;
let lastBalance = 0;
let balanceHistory: Array<{ balance: number; timestamp: number; source: string }> = [];

let cachedSolPrice = 150;
let cachedSolPriceTimestamp = 0;
let solPriceSource: "live" | "cached" | "default" = "default";

const TRANSACTION_LIMIT_WITHOUT_APPROVAL = 0.1;
const ABSOLUTE_MAX_TRANSACTION = 10;
let adminApprovedTransactions: Map<string, { toAddress: string; amountSOL: number; expiresAt: number }> = new Map();
let transactionLog: Array<{ timestamp: number; toAddress: string; amountSOL: number; signature?: string; verified: boolean; status: string }> = [];

export function approveTransaction(approvalId: string, toAddress: string, amountSOL: number): { success: boolean; approvalId: string } {
  const expiresAt = Date.now() + 5 * 60 * 1000;
  adminApprovedTransactions.set(approvalId, { toAddress, amountSOL, expiresAt });
  return { success: true, approvalId };
}

function cleanExpiredApprovals() {
  const now = Date.now();
  const keysToDelete: string[] = [];
  adminApprovedTransactions.forEach((approval, id) => {
    if (approval.expiresAt < now) {
      keysToDelete.push(id);
    }
  });
  keysToDelete.forEach(id => adminApprovedTransactions.delete(id));
}

function findApproval(toAddress: string, amountSOL: number): string | null {
  cleanExpiredApprovals();
  let foundId: string | null = null;
  adminApprovedTransactions.forEach((approval, id) => {
    if (!foundId && approval.toAddress === toAddress && approval.amountSOL >= amountSOL) {
      foundId = id;
    }
  });
  return foundId;
}

function verifyTransactionDetails(
  transaction: Transaction,
  expectedFrom: PublicKey,
  expectedTo: PublicKey,
  expectedLamports: number
): { valid: boolean; error?: string } {
  if (!transaction.instructions || transaction.instructions.length === 0) {
    return { valid: false, error: "Transaction has no instructions" };
  }

  const instruction = transaction.instructions[0];

  const programId = instruction.programId.toBase58();
  if (programId !== SystemProgram.programId.toBase58()) {
    return { valid: false, error: `Unexpected program: ${programId}, expected SystemProgram` };
  }

  const keys = instruction.keys;
  if (keys.length < 2) {
    return { valid: false, error: "Transaction instruction has insufficient account keys" };
  }

  const fromKey = keys[0].pubkey.toBase58();
  const toKey = keys[1].pubkey.toBase58();

  if (fromKey !== expectedFrom.toBase58()) {
    return { valid: false, error: `Source mismatch: expected ${expectedFrom.toBase58()}, got ${fromKey}` };
  }

  if (toKey !== expectedTo.toBase58()) {
    return { valid: false, error: `Destination mismatch: expected ${expectedTo.toBase58()}, got ${toKey}` };
  }

  const data = instruction.data;
  if (data.length >= 12) {
    const transferAmount = Number(data.readBigUInt64LE(4));
    if (transferAmount !== expectedLamports) {
      return { valid: false, error: `Amount mismatch: expected ${expectedLamports} lamports, got ${transferAmount}` };
    }
  }

  return { valid: true };
}

export function getTransactionLog() {
  return transactionLog.slice(-50);
}

export function getPendingApprovals() {
  cleanExpiredApprovals();
  const approvals: Array<{ id: string; toAddress: string; amountSOL: number; expiresAt: number }> = [];
  adminApprovedTransactions.forEach((approval, id) => {
    approvals.push({ id, ...approval });
  });
  return approvals;
}

function getSolPriceFallback(): { price: number; stale: boolean; source: "live" | "cached" | "default" } {
  const ageMs = Date.now() - cachedSolPriceTimestamp;
  const stale = cachedSolPriceTimestamp === 0 || ageMs > 5 * 60 * 1000;
  return { price: cachedSolPrice, stale, source: solPriceSource };
}

function updateCachedSolPrice(price: number) {
  cachedSolPrice = price;
  cachedSolPriceTimestamp = Date.now();
  solPriceSource = "live";
}

function getConnection(): Connection {
  if (!connection) {
    connection = new Connection(RPC_ENDPOINTS[0], "confirmed");
  }
  return connection;
}

function loadOrGenerateKeypair(): Keypair {
  if (fs.existsSync(GENERATED_KEY_PATH)) {
    const raw = fs.readFileSync(GENERATED_KEY_PATH, "utf-8");
    const arr = JSON.parse(raw);
    try {
      fs.chmodSync(GENERATED_KEY_PATH, 0o600);
    } catch {}
    console.log("[SOLWallet] Loaded keypair from disk");
    return Keypair.fromSecretKey(new Uint8Array(arr));
  }

  const kp = Keypair.generate();
  const dir = path.dirname(GENERATED_KEY_PATH);
  if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(GENERATED_KEY_PATH, JSON.stringify(Array.from(kp.secretKey)), { mode: 0o600 });
  console.log("[SOLWallet] Wallet initialized");
  return kp;
}

export function initializeWallet(): { success: boolean; address: string; autoGenerated?: boolean; error?: string } {
  try {
    const privateKey = process.env.SOL_PRIVATE_KEY;

    if (privateKey) {
      try {
        const decoded = bs58.decode(privateKey);
        walletKeypair = Keypair.fromSecretKey(decoded);
      } catch {
        try {
          const jsonKey = JSON.parse(privateKey);
          walletKeypair = Keypair.fromSecretKey(new Uint8Array(jsonKey));
        } catch {
          return { success: false, address: FATHER_ADDRESS, error: "Invalid private key format (expected base58 or JSON array)" };
        }
      }
      walletAutoGenerated = false;
      console.log(`[SOLWallet] Wallet initialized from SOL_PRIVATE_KEY: ${walletKeypair.publicKey.toBase58()}`);
    } else {
      walletKeypair = loadOrGenerateKeypair();
      walletAutoGenerated = true;
      console.log(`[SOLWallet] Auto-generated bot wallet: ${walletKeypair.publicKey.toBase58()}`);
      console.log(`[SOLWallet] Send SOL to this address to activate live trading`);
    }

    walletInitialized = true;
    const derivedAddress = walletKeypair.publicKey.toBase58();
    return { success: true, address: derivedAddress, autoGenerated: walletAutoGenerated };
  } catch (err: any) {
    return { success: false, address: FATHER_ADDRESS, error: err.message };
  }
}

export async function getBalance(): Promise<{ balance: number; lamports: number; usdEstimate: number; priceStale: boolean; priceSource: "live" | "cached" | "default" }> {
  try {
    const conn = getConnection();
    const pubkey = walletKeypair ? walletKeypair.publicKey : new PublicKey(FATHER_ADDRESS);
    const lamports = await conn.getBalance(pubkey);
    const balance = lamports / LAMPORTS_PER_SOL;

    let solPrice = cachedSolPrice;
    let priceStale = true;
    let priceSource: "live" | "cached" | "default" = solPriceSource;

    try {
      const { default: axios } = await import("axios");
      const priceRes = await axios.get("https://api.jup.ag/price/v2?ids=So11111111111111111111111111111111111111112", { timeout: 5000 });
      const jupPrice = priceRes.data?.data?.["So11111111111111111111111111111111111111112"]?.price;
      if (jupPrice) {
        solPrice = parseFloat(jupPrice);
        updateCachedSolPrice(solPrice);
        priceStale = false;
        priceSource = "live";
      }
    } catch {
      const fallback = getSolPriceFallback();
      solPrice = fallback.price;
      priceStale = fallback.stale;
      priceSource = fallback.source === "live" ? "cached" : fallback.source;
    }

    lastBalance = balance;
    balanceHistory.push({ balance, timestamp: Date.now(), source: "rpc_check" });
    if (balanceHistory.length > 100) balanceHistory = balanceHistory.slice(-100);

    return { balance, lamports, usdEstimate: balance * solPrice, priceStale, priceSource };
  } catch (err: any) {
    const fallback = getSolPriceFallback();
    return { balance: lastBalance, lamports: lastBalance * LAMPORTS_PER_SOL, usdEstimate: lastBalance * fallback.price, priceStale: fallback.stale, priceSource: fallback.source === "live" ? "cached" : fallback.source };
  }
}

export async function sendSOL(toAddress: string, amountSOL: number, options?: { adminApproved?: boolean; approvalId?: string }): Promise<{ success: boolean; signature?: string; error?: string; requiresApproval?: boolean }> {
  if (!walletKeypair) {
    return { success: false, error: "Wallet not initialized — SOL_PRIVATE_KEY required" };
  }
  if (amountSOL <= 0) {
    return { success: false, error: "Amount must be positive" };
  }
  if (amountSOL > ABSOLUTE_MAX_TRANSACTION) {
    transactionLog.push({ timestamp: Date.now(), toAddress, amountSOL, verified: false, status: "rejected_absolute_limit" });
    return { success: false, error: `Safety limit: max ${ABSOLUTE_MAX_TRANSACTION} SOL per transaction` };
  }

  if (amountSOL > TRANSACTION_LIMIT_WITHOUT_APPROVAL) {
    const existingApproval = options?.approvalId
      ? adminApprovedTransactions.get(options.approvalId)
      : null;
    const foundApprovalId = existingApproval ? options!.approvalId! : findApproval(toAddress, amountSOL);

    if (!options?.adminApproved && !foundApprovalId) {
      transactionLog.push({ timestamp: Date.now(), toAddress, amountSOL, verified: false, status: "requires_admin_approval" });
      console.log(`[SOLWallet] Transaction of ${amountSOL} SOL to ${toAddress} requires admin approval (limit: ${TRANSACTION_LIMIT_WITHOUT_APPROVAL} SOL)`);
      return {
        success: false,
        error: `Transaction of ${amountSOL} SOL exceeds ${TRANSACTION_LIMIT_WITHOUT_APPROVAL} SOL limit. Admin approval required.`,
        requiresApproval: true,
      };
    }

    if (foundApprovalId) {
      adminApprovedTransactions.delete(foundApprovalId);
      console.log(`[SOLWallet] Using admin approval ${foundApprovalId} for ${amountSOL} SOL to ${toAddress}`);
    }
  }

  try {
    const conn = getConnection();
    const toPubkey = new PublicKey(toAddress);
    const lamports = Math.floor(amountSOL * LAMPORTS_PER_SOL);

    const balance = await conn.getBalance(walletKeypair.publicKey);
    if (balance < lamports + 5000) {
      transactionLog.push({ timestamp: Date.now(), toAddress, amountSOL, verified: false, status: "insufficient_balance" });
      return { success: false, error: `Insufficient balance: ${balance / LAMPORTS_PER_SOL} SOL, need ${amountSOL} + fees` };
    }

    const transaction = new Transaction().add(
      SystemProgram.transfer({
        fromPubkey: walletKeypair.publicKey,
        toPubkey,
        lamports,
      })
    );

    const verification = verifyTransactionDetails(transaction, walletKeypair.publicKey, toPubkey, lamports);
    if (!verification.valid) {
      transactionLog.push({ timestamp: Date.now(), toAddress, amountSOL, verified: false, status: `verification_failed: ${verification.error}` });
      console.error(`[SOLWallet] Transaction verification failed: ${verification.error}`);
      return { success: false, error: `Transaction verification failed: ${verification.error}` };
    }

    console.log(`[SOLWallet] Transaction verified: ${amountSOL} SOL to ${toAddress} (${lamports} lamports)`);

    const signature = await sendAndConfirmTransaction(conn, transaction, [walletKeypair]);
    console.log(`[SOLWallet] Transfer complete: ${amountSOL} SOL to ${toAddress}, sig: ${signature}`);

    transactionLog.push({ timestamp: Date.now(), toAddress, amountSOL, signature, verified: true, status: "completed" });
    if (transactionLog.length > 200) transactionLog = transactionLog.slice(-200);

    balanceHistory.push({
      balance: (balance - lamports - 5000) / LAMPORTS_PER_SOL,
      timestamp: Date.now(),
      source: `transfer_to_${toAddress.slice(0, 8)}`
    });

    return { success: true, signature };
  } catch (err: any) {
    transactionLog.push({ timestamp: Date.now(), toAddress, amountSOL, verified: true, status: `error: ${err.message}` });
    return { success: false, error: err.message };
  }
}

export async function getRecentTransactions(limit = 10): Promise<any[]> {
  try {
    const conn = getConnection();
    const pubkey = walletKeypair ? walletKeypair.publicKey : new PublicKey(FATHER_ADDRESS);
    const signatures = await conn.getSignaturesForAddress(pubkey, { limit });
    return signatures.map(sig => ({
      signature: sig.signature,
      slot: sig.slot,
      blockTime: sig.blockTime,
      confirmationStatus: sig.confirmationStatus,
      err: sig.err,
    }));
  } catch (err: any) {
    return [];
  }
}

export function getKeypair(): Keypair | null {
  return walletKeypair;
}

export function isAutoGenerated(): boolean {
  return walletAutoGenerated;
}

export function getWalletState() {
  const priceFallback = getSolPriceFallback();
  return {
    initialized: walletInitialized,
    address: walletKeypair ? walletKeypair.publicKey.toBase58() : FATHER_ADDRESS,
    fatherAddress: FATHER_ADDRESS,
    communityAddress: COMMUNITY_ADDRESS,
    autoGenerated: walletAutoGenerated,
    lastBalance,
    balanceHistory: balanceHistory.slice(-20),
    canSign: !!walletKeypair,
    solPrice: {
      price: cachedSolPrice,
      stale: priceFallback.stale,
      source: priceFallback.source,
      lastUpdated: cachedSolPriceTimestamp > 0 ? new Date(cachedSolPriceTimestamp).toISOString() : null,
    },
  };
}

export async function depositProfitToWallet(amountSOL: number, source: string): Promise<{ success: boolean; signature?: string; error?: string }> {
  if (!walletKeypair) {
    return { success: false, error: "Wallet not initialized" };
  }
  const derivedAddress = walletKeypair.publicKey.toBase58();
  if (derivedAddress === FATHER_ADDRESS) {
    return { success: false, error: "Source and destination are the same wallet" };
  }
  return sendSOL(FATHER_ADDRESS, amountSOL);
}
