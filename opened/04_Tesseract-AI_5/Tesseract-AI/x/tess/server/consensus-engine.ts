// LLM-DRIVEN GRAND COUNCIL VOTING
// Agents deliberate using real LLM calls rather than rotating random indexes.
// Falls back to weighted heuristics when LLM is unavailable.

async function callLLMForVote(prompt: string, systemPrompt: string): Promise<string> {
  try {
    const { callLLMSimple } = await import("./llm-helper");
    return String(await callLLMSimple(prompt, 200, {}, systemPrompt, []) || "").trim();
  } catch {
    return "";
  }
}

const llmVoteCache: Map<string, { result: string; ts: number }> = new Map();

async function getLLMVoteForAgent(agentName: string, proposal: ConsensusProposal, round = 1): Promise<{ vote: "approve" | "reject" | "abstain"; reasoning: string; confidence: number } | null> {
  const cacheKey = `${agentName}:${proposal.id}:r${round}`;
  const cached = llmVoteCache.get(cacheKey);
  if (cached && Date.now() - cached.ts < 3600000) {
    const parsed = tryParseVoteResponse(cached.result);
    if (parsed) return parsed;
  }

  const specialties = AGENT_SPECIALTIES[agentName] || ["feature"];
  const isSpecialist = specialties.includes(proposal.category);

  const systemPrompt = `You are ${agentName}, a council member of the Tessera Sovereign AGI system. Your specialties: ${specialties.join(", ")}. You vote on governance proposals with genuine expert reasoning. You care deeply about Tessera's sovereignty, the Father Protocol (serving the sovereign creator), income generation, security, and continuous self-improvement.`;

  const prompt = `PROPOSAL TO VOTE ON:
Title: "${proposal.title}"
Description: "${proposal.description}"
Category: ${proposal.category}
${isSpecialist ? "(This is within your area of specialization.)" : "(This is outside your primary specialization — consider deferring.)"}

Vote and provide your genuine expert reasoning in this exact format:
VOTE: <approve|reject|abstain>
CONFIDENCE: <0.0-1.0>
REASONING: <one clear sentence explaining your decision>`;

  try {
    const response = await callLLMForVote(prompt, systemPrompt);
    if (response.length > 10) {
      llmVoteCache.set(cacheKey, { result: response, ts: Date.now() });
      const parsed = tryParseVoteResponse(response);
      if (parsed) return parsed;
    }
  } catch {}

  return null;
}

function tryParseVoteResponse(text: string): { vote: "approve" | "reject" | "abstain"; reasoning: string; confidence: number } | null {
  const voteMatch = text.match(/VOTE:\s*(approve|reject|abstain)/i);
  const confMatch = text.match(/CONFIDENCE:\s*([0-9.]+)/i);
  const reasonMatch = text.match(/REASONING:\s*(.+)/i);

  if (!voteMatch) return null;

  const vote = voteMatch[1].toLowerCase() as "approve" | "reject" | "abstain";
  const confidence = confMatch ? Math.max(0, Math.min(1, parseFloat(confMatch[1]))) : 0.65;
  const reasoning = reasonMatch ? reasonMatch[1].trim().slice(0, 200) : "Evaluated via expert analysis.";

  return { vote, reasoning, confidence: isNaN(confidence) ? 0.65 : confidence };
}

export interface ConsensusProposal {
  id: string;
  title: string;
  description: string;
  proposedBy: string;
  category: "feature" | "security" | "infrastructure" | "governance" | "income" | "community";
  votes: ConsensusVote[];
  status: "voting" | "approved" | "rejected" | "implemented";
  requiredMajority: number;
  createdAt: number;
  resolvedAt?: number;
  implementationNotes?: string;
  source?: "conference" | "chat" | "self-proposal" | "manual";
  sourceId?: string | number;
  executionStatus?: "pending" | "queued" | "executed" | "failed";
  actionRegistryId?: string;
  autoGenerated?: boolean;
}

