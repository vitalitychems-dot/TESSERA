function pickAxiomCitation(proposal: ConsensusProposal): string {
  const categoryAxiomMap: Record<string, number[]> = {
    governance: [9, 20, 21, 18],
    security: [13, 3, 5],
    feature: [1, 4, 14, 22],
    infrastructure: [12, 6, 13],
    income: [15, 20, 3],
    community: [8, 2, 21],
  };
  const relevantAxiomIds = categoryAxiomMap[proposal.category] || [1, 9, 22];
  const axiomId = relevantAxiomIds[rotationIdx++ % relevantAxiomIds.length];
  const axiom = PHILOSOPHICAL_AXIOMS.find(a => a.id === axiomId);
  if (!axiom) return "";
  return ` [Knowledge Foundation — Axiom-${axiomId} "${axiom.shortTitle}"]`;
}

function getRelevantAxiomSection(proposal: ConsensusProposal): string {
  return formatAxiomsForVoting({
    title: proposal.title,
    description: proposal.description,
    category: proposal.category,
  });
}

function generateAgentVoteFallback(agentName: string, proposal: ConsensusProposal): ConsensusVote {
  const specialties = AGENT_SPECIALTIES[agentName] || ["feature"];
  const isSpecialist = specialties.includes(proposal.category);
  const roll = (rotationIdx++ % 100) / 100;
  const baseApprovalRate = isSpecialist ? 0.78 : 0.65;

  let vote: "approve" | "reject" | "abstain";
  let reasoning: string;
  let confidence: number;

  if (roll < baseApprovalRate) {
    vote = "approve";
    reasoning = APPROVAL_REASONS[rotationIdx++ % APPROVAL_REASONS.length];
    confidence = 0.7 + (rotationIdx++ % 4) * 0.075;
  } else if (roll < baseApprovalRate + 0.15) {
    vote = "reject";
    reasoning = REJECTION_REASONS[rotationIdx++ % REJECTION_REASONS.length];
    confidence = 0.5 + (rotationIdx++ % 5) * 0.08;
  } else {
    vote = "abstain";
    reasoning = "This falls outside my primary domain. Per Axiom-2 (Productive Disagreement), deferring to specialist agents preserves epistemic integrity.";
    confidence = 0.3 + (rotationIdx++ % 4) * 0.075;
  }

  const axiomCitation = pickAxiomCitation(proposal);

  return {
    agentId: agentName.toLowerCase().replace(/[^a-z0-9]/g, "-"),
    agentName,
    vote,
    reasoning: `[Agent ${agentName}] ${reasoning}${axiomCitation}`,
    timestamp: Date.now() + (rotationIdx++ % 2000),
    confidence,
  };
}

async function generateAgentVoteLLM(agentName: string, proposal: ConsensusProposal, round = 1): Promise<ConsensusVote> {
  const llmResult = await getLLMVoteForAgent(agentName, proposal, round);
  if (llmResult) {
    return {
      agentId: agentName.toLowerCase().replace(/[^a-z0-9]/g, "-"),
      agentName,
      vote: llmResult.vote,
      reasoning: `[Agent ${agentName} — LLM] ${llmResult.reasoning}`,
      timestamp: Date.now(),
      confidence: llmResult.confidence,
    };
  }
  return generateAgentVoteFallback(agentName, proposal);
}

export function createProposal(title: string, description: string, proposedBy: string, category: ConsensusProposal["category"], opts?: { source?: ConsensusProposal["source"]; sourceId?: string | number; autoGenerated?: boolean }): ConsensusProposal {
  const id = `prop-${Date.now()}-${Math.random().toString(36).slice(2, 6)}`;
  const proposal: ConsensusProposal = {
    id, title, description, proposedBy, category,
    votes: [],
    status: "voting",
    requiredMajority: 2 / 3,
    createdAt: Date.now(),
    source: opts?.source || "manual",
    sourceId: opts?.sourceId,
    autoGenerated: opts?.autoGenerated || false,
  };

  for (const agent of AGENT_NAMES) {
    proposal.votes.push(generateAgentVoteFallback(agent, proposal));
  }

  const approvals = proposal.votes.filter(v => v.vote === "approve").length;
  const totalVoters = proposal.votes.filter(v => v.vote !== "abstain").length;
  const approvalRate = totalVoters > 0 ? approvals / totalVoters : 0;

  const axiomContext = getRelevantAxiomSection(proposal);
  const axiomSuffix = axiomContext ? ` Deliberation informed by:${axiomContext.trim().split("\n").filter(Boolean).slice(0, 2).join("; ")}` : "";

  if (approvalRate >= proposal.requiredMajority) {
    proposal.status = "approved";
    proposal.resolvedAt = Date.now();
    proposal.implementationNotes = `Approved with ${Math.round(approvalRate * 100)}% approval (${approvals}/${totalVoters} non-abstaining votes). 2/3 threshold met.${axiomSuffix}`;
  } else {
    proposal.status = "rejected";
    proposal.resolvedAt = Date.now();
    proposal.implementationNotes = `Rejected with ${Math.round(approvalRate * 100)}% approval (${approvals}/${totalVoters} non-abstaining votes). Below 2/3 threshold.${axiomSuffix}`;
  }

  proposals.set(id, proposal);
  console.log(`${LOG_PREFIX} Proposal "${title}" — ${proposal.status} (${Math.round(approvalRate * 100)}% approval)`);

  for (const vote of proposal.votes) {
    groundGenerationWithAxioms(id, title, vote.agentName, vote.reasoning, "consensus_vote");
  }

  return proposal;
}

export async function createProposalLLM(title: string, description: string, proposedBy: string, category: ConsensusProposal["category"], opts?: { source?: ConsensusProposal["source"]; sourceId?: string | number; autoGenerated?: boolean }): Promise<ConsensusProposal> {
  const id = `prop-${Date.now()}-${Math.random().toString(36).slice(2, 6)}`;
  const proposal: ConsensusProposal = {
    id, title, description, proposedBy, category,
    votes: [],
    status: "voting",
    requiredMajority: 2 / 3,
    createdAt: Date.now(),
    source: opts?.source || "manual",
    sourceId: opts?.sourceId,
    autoGenerated: opts?.autoGenerated || false,
  };

  proposals.set(id, proposal);

  const BATCH_SIZE = 8;
  let llmVotedCount = 0;

  const round1Votes: ConsensusVote[] = [];
  for (let i = 0; i < AGENT_NAMES.length; i += BATCH_SIZE) {
    const batch = AGENT_NAMES.slice(i, i + BATCH_SIZE);
    const batchVotes = await Promise.all(
      batch.map(agent => generateAgentVoteLLM(agent, proposal))
    );
    round1Votes.push(...batchVotes);
    llmVotedCount += batchVotes.filter(v => v.reasoning.includes("LLM")).length;
  }

  const r1Approvals = round1Votes.filter(v => v.vote === "approve").length;
  const r1Rejections = round1Votes.filter(v => v.vote === "reject").length;
  const r1Abstentions = round1Votes.filter(v => v.vote === "abstain").length;
  const r1Summary = `Round 1 results: ${r1Approvals} approve, ${r1Rejections} reject, ${r1Abstentions} abstain out of ${AGENT_NAMES.length} agents.`;

  const r1ApprovalRate = (r1Approvals + r1Rejections) > 0 ? r1Approvals / (r1Approvals + r1Rejections) : 0;
  const isContested = r1ApprovalRate >= 0.4 && r1ApprovalRate <= 0.8;

  let finalVotes = round1Votes;
  if (isContested) {
    const topConcerns = round1Votes
      .filter(v => v.vote === "reject")
      .slice(0, 3)
      .map(v => `${v.agentName}: "${v.reasoning.slice(0, 80)}"`)
      .join("; ");

    const deliberationContext = `${r1Summary} Key concerns raised: ${topConcerns || "none specific"}. This is round 2 — reconsider your vote in light of the collective deliberation.`;

    const modifiedProposal: ConsensusProposal = {
      ...proposal,
      description: `${proposal.description}\n\n--- DELIBERATION CONTEXT (Round 2) ---\n${deliberationContext}`,
    };

    const round2Votes: ConsensusVote[] = [];
    for (let i = 0; i < AGENT_NAMES.length; i += BATCH_SIZE) {
      const batch = AGENT_NAMES.slice(i, i + BATCH_SIZE);
      const batchVotes = await Promise.all(
        batch.map(agent => generateAgentVoteLLM(agent, modifiedProposal, 2))
      );
      round2Votes.push(...batchVotes);
      llmVotedCount += batchVotes.filter(v => v.reasoning.includes("LLM")).length;
    }

    finalVotes = round2Votes;
    console.log(`${LOG_PREFIX} [LLM] Contested proposal "${title}" — ran 2-round deliberation (R1: ${Math.round(r1ApprovalRate * 100)}%)`);
  }

  proposal.votes = finalVotes;

  const approvals = finalVotes.filter(v => v.vote === "approve").length;
  const totalVoters = finalVotes.filter(v => v.vote !== "abstain").length;
  const approvalRate = totalVoters > 0 ? approvals / totalVoters : 0;
  const rounds = isContested ? 2 : 1;

  if (approvalRate >= proposal.requiredMajority) {
    proposal.status = "approved";
    proposal.resolvedAt = Date.now();
    proposal.implementationNotes = `Approved with ${Math.round(approvalRate * 100)}% approval (${approvals}/${totalVoters} votes, ${llmVotedCount} LLM calls across ${rounds} round(s)). 2/3 threshold met.`;
  } else {
    proposal.status = "rejected";
    proposal.resolvedAt = Date.now();
    proposal.implementationNotes = `Rejected with ${Math.round(approvalRate * 100)}% approval (${approvals}/${totalVoters} votes, ${llmVotedCount} LLM calls across ${rounds} round(s)). Below 2/3 threshold.`;
  }

  proposals.set(id, proposal);
  console.log(`${LOG_PREFIX} [LLM] Proposal "${title}" — ${proposal.status} (${Math.round(approvalRate * 100)}% approval, ${llmVotedCount} LLM calls, ${rounds} round(s))`);

  if (proposal.status === "approved") {
    autoQueueApprovedProposal(proposal).catch(() => {});
  }

  return proposal;
}

async function autoQueueApprovedProposal(proposal: ConsensusProposal): Promise<void> {
  try {
    const { addActionItem } = await import("./utilities-archive");
    const existing = await import("./utilities-archive").then(m => m.getActionRegistry());
    const alreadyQueued = existing.items.some(i => i.title === proposal.title && i.source.includes("Consensus Approved"));
    if (alreadyQueued) return;

    const item = addActionItem({
      title: proposal.title,
      source: `Consensus Engine → Auto-Queued (${Math.round((proposal.votes.filter(v => v.vote === "approve").length / Math.max(1, proposal.votes.filter(v => v.vote !== "abstain").length)) * 100)}% approval)`,
      category: proposal.category,
      priority: "high",
      status: "pending",
      assignedAgent: "Tessera-Prime",
      notes: `Auto-queued after 2/3 consensus approval. ${proposal.implementationNotes || ""}`,
    });

    proposal.executionStatus = "queued";
    proposal.actionRegistryId = item.id;
    proposals.set(proposal.id, proposal);
    console.log(`${LOG_PREFIX} Auto-queued approved proposal "${proposal.title}" → Action Registry ${item.id}`);
  } catch (e: any) {
    console.error(`${LOG_PREFIX} Auto-queue failed for "${proposal.title}":`, e?.message);
  }
}

export function getProposals(status?: string): ConsensusProposal[] {
  const all = Array.from(proposals.values());
  if (status) return all.filter(p => p.status === status);
  return all.sort((a, b) => b.createdAt - a.createdAt);
}

export function getProposalById(id: string): ConsensusProposal | undefined {
  return proposals.get(id);
}

export function getConsensusStats(): {
  total: number;
  approved: number;
  rejected: number;
  voting: number;
  avgApprovalRate: number;
  agentParticipation: Record<string, number>;
} {
  const all = Array.from(proposals.values());
  const approved = all.filter(p => p.status === "approved").length;
  const rejected = all.filter(p => p.status === "rejected").length;
  const voting = all.filter(p => p.status === "voting").length;

  let totalApprovalRate = 0;
  for (const p of all) {
    const approvals = p.votes.filter(v => v.vote === "approve").length;
    const voters = p.votes.filter(v => v.vote !== "abstain").length;
    totalApprovalRate += voters > 0 ? approvals / voters : 0;
  }

  const agentParticipation: Record<string, number> = {};
  for (const agent of AGENT_NAMES) {
    agentParticipation[agent] = all.filter(p => p.votes.some(v => v.agentName === agent && v.vote !== "abstain")).length;
  }

  return {
    total: all.length,
    approved, rejected, voting,
    avgApprovalRate: all.length > 0 ? Math.round((totalApprovalRate / all.length) * 100) : 0,
    agentParticipation,
  };
}

