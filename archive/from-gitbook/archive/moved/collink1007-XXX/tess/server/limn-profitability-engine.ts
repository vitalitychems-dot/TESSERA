function calculateTotals() {
  let totalLow = 0;
  let totalHigh = 0;
  let active = 0;

  for (const s of state.strategies) {
    const match = s.estimatedMonthlyUsd.match(/(\d+)-?(\d+)?/);
    if (match) {
      totalLow += parseInt(match[1]) || 0;
      totalHigh += parseInt(match[2] || match[1]) || 0;
    }
    if (s.status === "active" || s.status === "generating" || s.status === "in-progress") {
      active++;
    }
  }

  state.totalEstimatedMonthlyUsd = Math.round((totalLow + totalHigh) / 2);
  state.activeStrategies = active;
}

function loadState() {
  try {
    if (fs.existsSync(STATE_FILE)) {
      const saved = JSON.parse(fs.readFileSync(STATE_FILE, "utf-8"));
      for (const saved_s of saved.strategies || []) {
        const local = state.strategies.find(s => s.id === saved_s.id);
        if (local) {
          local.status = saved_s.status;
          local.priority = saved_s.priority;
        }
      }
      state.lastUpdated = saved.lastUpdated || Date.now();
    }
  } catch {}
}

function saveState() {
  try {
    fs.writeFileSync(STATE_FILE, JSON.stringify({
      strategies: state.strategies.map(s => ({ id: s.id, status: s.status, priority: s.priority })),
      lastUpdated: Date.now(),
    }));
  } catch {}
}

