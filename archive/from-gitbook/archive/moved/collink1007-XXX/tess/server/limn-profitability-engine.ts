export function updateStrategyStatus(id: number, status: ProfitabilityStrategy["status"]) {
  const strategy = state.strategies.find(s => s.id === id);
  if (!strategy) return null;
  strategy.status = status;
  state.lastUpdated = Date.now();
  saveState();
  return strategy;
}

export function getStrategyById(id: number) {
  return state.strategies.find(s => s.id === id) || null;
}

export function getStrategiesByCategory(category: string) {
  return state.strategies.filter(s => s.category.toLowerCase().includes(category.toLowerCase()));
}

export function getPriorityStrategies(maxPriority: number = 2) {
  return state.strategies.filter(s => s.priority <= maxPriority).sort((a, b) => a.priority - b.priority);
}

export function getAutomatableStrategies() {
  return state.strategies.filter(s => s.automatable && !s.requiresHuman).sort((a, b) => a.priority - b.priority);
}

