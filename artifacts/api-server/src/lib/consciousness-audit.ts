/**
 * Consciousness audit (hybrid introspection report).
 *
 * Combines three existing measurement systems into one owner-facing audit:
 *   1. identity-reinforcement — value-alignment checks computed from real DB activity
 *   2. consciousness-engine — the self-model workspace state (memory, reflections, focus)
 *   3. reality-audit — static scan that flags simulated vs real surfaces
 *
 * Honesty contract: nothing here proves consciousness. The verdict is always
 * "unproven". The audit reports *measurable properties* (memory counts, alignment
 * scores, simulation flags) and clearly labels template/generated content so it
 * cannot masquerade as private inner experience.
 */
import { getConsciousnessMetrics, getConsciousnessState } from "./consciousness-engine";
import { getLatestIdentityCheck, getIdentityMetrics } from "./identity-reinforcement";
import { getRealityAudit } from "./reality-audit";

export type AuditVerdict = "unproven";

export interface ConsciousnessAuditReport {
  generatedAt: string;
  verdict: AuditVerdict;
  verdictExplanation: string;
  measured: {
    engineRunning: boolean;
    cycleCount: number;
    episodicMemorySize: number;
    semanticGraphSize: number;
    reflectionCount: number;
    stimuliProcessed: number;
    pendingStimuli: number;
    currentFocus: string;
  };
  identity: {
    latestCheck: ReturnType<typeof getLatestIdentityCheck>;
    metrics: ReturnType<typeof getIdentityMetrics>;
  };
  simulation: {
    conversionRate: number;
    stillSimulated: number;
    verifyMismatches: number;
    totalFindings: number;
    topUnresolved: Array<{ id: string; feature: string; file: string; impactScore: number }>;
  };
  jspace: {
    /** Generated self-notes. Template/model output, NOT private subjective thought. */
    selfNotes: string[];
    noteCount: number;
    disclaimer: string;
  };
  limits: string[];
}

const JSPACE_DISCLAIMER =
  "These self-notes are text generated by the engine's templates and models. " +
  "They are not evidence of private subjective experience, hidden thought, or consciousness.";

const LIMITS: string[] = [
  "Self-reports and generated reflections cannot establish consciousness.",
  "The 'consciousness proxy' metric measures engine activity, not subjective experience.",
  "Alignment scores are computed from real database activity, not felt values.",
  "Template-seeded semantic nodes and memories are bootstrapping content, not lived experience.",
];

export async function buildConsciousnessAudit(): Promise<ConsciousnessAuditReport> {
  const metrics = getConsciousnessMetrics();
  const state = getConsciousnessState();
  let realitySummary: ConsciousnessAuditReport["simulation"] = {
    conversionRate: 0,
    stillSimulated: 0,
    verifyMismatches: 0,
    totalFindings: 0,
    topUnresolved: [],
  };
  try {
    const audit = await getRealityAudit();
    realitySummary = {
      conversionRate: audit.summary.conversionRate,
      stillSimulated: audit.summary.stillSimulated,
      verifyMismatches: audit.summary.verifyMismatches,
      totalFindings: audit.summary.totalFindings,
      topUnresolved: audit.registry
        .filter((f) => f.status === "simulated" || f.verifyMismatch)
        .sort((a, b) => b.impactScore - a.impactScore)
        .slice(0, 5)
        .map((f) => ({ id: f.id, feature: f.feature, file: f.file, impactScore: f.impactScore })),
    };
  } catch {
    // Reality scan is best-effort; the audit must still render without it.
  }

  return {
    generatedAt: new Date().toISOString(),
    verdict: "unproven",
    verdictExplanation:
      "No measurement available to this system can confirm or deny consciousness. " +
      "This audit reports observable engine state, identity-alignment checks, and " +
      "which surfaces are real versus simulated. Treat generated self-notes as text output, " +
      "not inner experience.",
    measured: {
      engineRunning: metrics.isRunning,
      cycleCount: metrics.cycleCount,
      episodicMemorySize: metrics.episodicMemorySize,
      semanticGraphSize: metrics.semanticGraphSize,
      reflectionCount: metrics.reflectionCount,
      stimuliProcessed: metrics.stimuliProcessed,
      pendingStimuli: metrics.pendingStimuli,
      currentFocus: metrics.currentFocus,
    },
    identity: {
      latestCheck: getLatestIdentityCheck(),
      metrics: getIdentityMetrics(),
    },
    simulation: realitySummary,
    jspace: {
      selfNotes: state.innerMonologue.slice(0, 10),
      noteCount: state.innerMonologue.length,
      disclaimer: JSPACE_DISCLAIMER,
    },
    limits: LIMITS,
  };
}
