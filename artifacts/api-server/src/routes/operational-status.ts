import { Router, type IRouter } from "express";
import { isDbConfigured, probeDatabase } from "@workspace/db";

type ServiceState = "available" | "unavailable" | "not-configured" | "unverified";
type Probe = () => Promise<void>;

export async function getOperationalStatus(options: {
  databaseConfigured?: boolean;
  probeDatabase?: Probe;
  now?: () => Date;
} = {}) {
  const checkedAt = (options.now ?? (() => new Date()))().toISOString();
  const databaseConfigured = options.databaseConfigured ?? isDbConfigured();
  let databaseState: ServiceState = "not-configured";
  let databaseSource = "DATABASE_URL is not configured; no database connection was attempted.";

  if (databaseConfigured) {
    try {
      await (options.probeDatabase ?? probeDatabase)();
      databaseState = "available";
      databaseSource = "A temporary PostgreSQL connection completed SELECT 1.";
    } catch {
      databaseState = "unavailable";
      databaseSource = "A live PostgreSQL SELECT 1 probe failed; connection details are withheld.";
    }
  }

  return {
    checkedAt,
    api: {
      state: "available" as const,
      source: "This response was generated by the running API process.",
    },
    database: { state: databaseState, source: databaseSource },
    model: {
      state: "unverified" as const,
      source: "No model reachability check was performed; configuration alone does not prove availability.",
    },
    worker: {
      state: "unverified" as const,
      source: "No independent worker heartbeat is configured for this status endpoint.",
    },
  };
}

export function createOperationalStatusRouter(): IRouter {
  const router: IRouter = Router();
  router.get("/operational-status", async (_req, res) => {
    res.setHeader("Cache-Control", "no-store");
    res.json(await getOperationalStatus());
  });
  return router;
}

const router = createOperationalStatusRouter();
export default router;
