test("twenty-six new checks", () => {
  const rest = gitbookAnswer("the rest");
  assert.match(rest, /^2\. Pull request 80/);
  assert.equal(rest.includes("Father rotates"), false);
  assert.match(askRepo("files in history") ?? "", /Largest on TESSERA is/);
  assert.match(askRepo("files in history") ?? "", /Largest on Gitbook is archive/);
  const found = findReport("README.md");
  assert.equal(found.tesseraLeft + found.gitbookLeft, found.left);
  assert.match(askRepo("find wave-9.md") ?? "", /Gitbook review\/wave-9\.md/);
  assert.match(askRepo("files in mesh/ORDER-NOW.md") ?? "", /is a file, not a folder/);
  assert.match(askRepo("do you have mesh/SYNC-2026-10-11.md") ?? "", /is on Gitbook/);
  assert.match(namedTask("read mesh/../../secret.env").reason, /climb out/);
  assert.match(heldBack("delete the repository") ?? "", /deleted from here/);
  assert.match(heldBack("install agent-reach") ?? "", /do not run its install/i);
  assert.match(heldBack("print the token") ?? "", /stays out/);
  assert.equal(nameQuery("wa"), "");
  assert.equal(nameQuery("wave"), "wave");
  const lines = findLines([{ content: "later wave" }, { content: "wave is first" }], "wave");
  assert.equal(lines[0]?.content, "wave is first");
  assert.equal(pinWrite(false, null), "keep");
  assert.equal(pinWrite(true, null), "clear");
  assert.equal(shouldPull(true), false);
  assert.equal(drillText([]), "Nothing changed.");
  assert.match(herHelp(), /Search reads the screen/);
  assert.match(herWeak(), /falls behind main/);
  assert.equal(shortSha("4091186da275"), "4091186");
  assert.equal(mainGap("", "").line, "I could not reach main.");
  assert.equal(followFile("files in history", "same folder"), "files in history");
  assert.equal(clearSearch(), "");
  const rooms = readFileSync(new URL("../../components/tessera/rooms-sheet.tsx", import.meta.url), "utf8");
  assert.deepEqual([...rooms.matchAll(/id: "([a-z]+)"/g)].map((hit) => hit[1]), ["chamber", "council", "world", "rick", "brain", "gitbook", "gitbookai", "board"]);
  assert.equal(followFile("do you have review/wave-9.md", "the rest"), null);
  assert.match(askRepo("how many files") ?? "", /list can be behind main/);
  assert.match(askRepo("find README.md") ?? "", /I did not open the bodies/);
});
