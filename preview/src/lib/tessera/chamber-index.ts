export function chamberPicture() {
  const first = CHAMBER_FILES[0] ?? "none";
  const last = CHAMBER_FILES[CHAMBER_FILES.length - 1] ?? "none";
  return `${CHAMBER_FILES.length} files are in this chamber. First ${first}. Last ${last}.`;
}

export function chamberHolds(name: string) {
  const q = name.trim().toLowerCase();
  const hit = CHAMBER_FILES.find((file) => file.toLowerCase().includes(q));
  return hit ? `Yes. ${hit} is here.` : `No. ${name.trim() || "That"} is not in this chamber.`;
}
