import assert from "node:assert/strict";
import test from "node:test";
import { addedLines, skillDrill } from "./skill-drill.ts";
import { findReport, largestFolder } from "./repo-ask.ts";
import { pinLine } from "./find-line.ts";
import { followFile } from "./file-follow.ts";
import { namedTask } from "./named-task.ts";
import { mainGap } from "./main-gap.ts";
import { heldBack } from "./scope-stop.ts";
import { sameDesk } from "./desk-same.ts";
import { cardAllowed } from "./self-ingest.ts";
import { readFileSync } from "node:fs";

test("the twenty changes hold", () => {
  const drill = skillDrill();
  assert.equal(addedLines([], drill.lines).length, drill.lines.length);
  assert.equal(addedLines(drill.lines, drill.lines).length, 0);
  const found = findReport("README.md");
  assert.ok(found.left > 0);
  assert.equal(largestFolder("gitbook").name, "archive");
  assert.equal(pinLine("m1", "m2"), "m2");
  assert.equal(pinLine("m1", "m1"), null);
  assert.equal(followFile("do you have review/wave-9.md", "again"), "do you have review/wave-9.md");
  assert.equal(followFile("do you have review/wave-9.md", "and README.md"), "do you have README.md");
  assert.equal(namedTask("read mesh/ORDER-NOW.md").open, true);
  assert.equal(namedTask("read mesh/secret.env").open, false);
  assert.match(namedTask("read one and mesh/a.md and mesh/b.md").reason, /Name one file/);
  const gap = mainGap("bbbbbbbbbbbb", "cccccccccccc");
  assert.equal(gap.boardDiffers, true);
  assert.equal(gap.tesseraMoved, true);
  assert.match(heldBack("take the copilot seat") ?? "", /Copilot/);
  assert.match(heldBack("merge the weights") ?? "", /unmerged/);
  assert.match(heldBack("open a protected body") ?? "", /unopened/);
  assert.match(heldBack("rotate the keys") ?? "", /Father/);
  assert.equal(heldBack("how many files"), null);
  assert.equal(sameDesk([{ at: "1", text: "a" }], [{ at: "1", text: "a" }]), true);
  assert.equal(sameDesk([{ at: "1", text: "a" }], [{ at: "1", text: "b" }]), false);
  assert.equal(cardAllowed("her-rules.txt"), true);
  assert.equal(cardAllowed("weights.ts"), false);
  const chamber = readFileSync(new URL("./../../components/tessera/chamber.tsx", import.meta.url), "utf8");
  const ask = readFileSync(new URL("./ask-all.ts", import.meta.url), "utf8");
  assert.equal(/from ["']@\/lib\/tessera\/(herself-v3|herself-v4|repo-ask|gitbook-paths|tessera-paths)["']/.test(chamber), false);
  assert.equal(/from ["']\.\/repo-ask/.test(ask), false);
});
